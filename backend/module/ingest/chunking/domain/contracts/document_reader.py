from collections.abc import Iterator
from contextlib import AbstractContextManager
from pathlib import Path
from typing import Protocol

from shared.ingestion.document import ContentBlock, ExtractedTable


class CoverageRecorder(Protocol):
    def record_text(self, block_id: str, start: int, end: int, text: str) -> None: ...
    def record_cell(self, table_id: str, row: int, column: int, start: int, end: int, text: str) -> None: ...
    def record_rows(self, table_id: str, start: int, end: int) -> None: ...
    def record_caption(self, table_id: str, start: int, end: int, text: str) -> None: ...
    def finish_coverage(self) -> None: ...


class IndexedContent(CoverageRecorder, Protocol):
    title: str | None

    def blocks(self) -> Iterator[ContentBlock]: ...
    def sections(self) -> list[tuple[str, str | None, int, str]]: ...  # (id, parent_id, level, title)
    def table(self, table_id: str) -> ExtractedTable: ...
    def section_context(self, section_id: str | None, level: int | None) -> tuple[str | None, tuple[str, ...]]: ...


class DocumentReader(Protocol):
    def open(self, path: Path) -> AbstractContextManager[IndexedContent]: ...
